   * ВАЖНО ПРО ВНЕШНИЙ АДРЕС В СПИСКЕ. clientIp() доверяет заголовкам
   * X-Real-IP / X-Forwarded-For, когда запрос пришёл с приватного адреса - то
   * есть всегда, если Качалка стоит за обратным прокси. Отсюда два требования
   * к пограничному nginx:
   *
   *   proxy_set_header X-Real-IP $remote_addr;   # обязателен, он и авторитетен
   *
   * Стандартный Debian-овский proxy_params эту строку содержит, и proxy_set_header
   * ЗАМЕЩАЕТ присланный клиентом заголовок - подделать его снаружи нельзя. А вот
   * X-Forwarded-For там собирается через $proxy_add_x_forwarded_for, то есть
   * ДОПИСЫВАЕТ клиентское значение, поэтому clientIp() берёт из него последний
   * элемент (его добавил сам прокси), а не первый. Раньше брался первый, и запрос
   * с подставленным в этот заголовок доверенным адресом выдавал себя за него.
   *
   * Проверить свой прокси: grep -rn "X-Real-IP\|X-Forwarded-For" /etc/nginx/
   *
   * Остаётся один путь подделки - прямое обращение к порту контейнера (8000/25567)
   * с приватного адреса, минуя nginx. Кто это может, и так уже в домашней сети,
   * которая в списке ниже.
   *
   * 'feedbackAdminNetworks' => ['127.0.0.1/32', '::1/128', '192.168.1.0/24']
   */
  'feedbackAdminNetworks' => getenv('FEEDBACK_ADMIN_NETWORKS') !== false
      ? array_filter(array_map('trim', explode(',', getenv('FEEDBACK_ADMIN_NETWORKS'))))
      : [
          '127.0.0.1/32',   // сам контейнер
          '::1/128',
          '192.168.1.0/24', // домашняя сеть
        ],

  /**
   * Защита пароля от перебора: сколько неудачных попыток на источник за окно.
   * Считаются только неудачи - верный пароль счётчик не трогает.
   *
   * 'feedbackAdminTries' => 5, 'feedbackAdminTriesWindow' => 600
   */
  'feedbackAdminTries' => 5,
  'feedbackAdminTriesWindow' => 600
  );
